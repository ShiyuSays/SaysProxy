package com.saysproxy.v3.common;

import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.security.AlgorithmParameters;
import java.security.GeneralSecurityException;
import java.security.KeyFactory;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.MessageDigest;
import java.security.PrivateKey;
import java.security.PublicKey;
import java.security.SecureRandom;
import java.security.interfaces.ECPublicKey;
import java.security.spec.ECFieldFp;
import java.security.spec.ECGenParameterSpec;
import java.security.spec.ECParameterSpec;
import java.security.spec.ECPoint;
import java.security.spec.ECPublicKeySpec;
import java.security.spec.EllipticCurve;
import java.util.Arrays;
import javax.crypto.Cipher;
import javax.crypto.KeyAgreement;
import javax.crypto.Mac;
import javax.crypto.spec.GCMParameterSpec;
import javax.crypto.spec.SecretKeySpec;

/**
 * Small, dependency-free crypto helper for the protocol.
 *
 * Design:
 *  - ECDH on NIST P-256 provides forward secrecy.
 *  - PBKDF2-HMAC-SHA256 turns the server connection password into a PSK.
 *  - HKDF-HMAC-SHA256 derives directional AES-256-GCM keys.
 *  - The server proves knowledge of the password before the client sends the
 *    account credentials.
 *
 * The server connection password is randomly generated by the server and is
 * high entropy. Do not replace it with a short human password.
 */
public final class Crypto {
    private static final SecureRandom RANDOM = new SecureRandom();
    private static final ECParameterSpec P256;
    private static final int P256_FIELD_BYTES = 32;

    static {
        try {
            AlgorithmParameters params = AlgorithmParameters.getInstance("EC");
            params.init(new ECGenParameterSpec("secp256r1"));
            P256 = params.getParameterSpec(ECParameterSpec.class);
        } catch (GeneralSecurityException e) {
            throw new ExceptionInInitializerError(e);
        }
    }

    private Crypto() {
    }

    public static byte[] randomBytes(int length) {
        byte[] out = new byte[length];
        RANDOM.nextBytes(out);
        return out;
    }

    public static byte[] sha256(byte[] data) {
        try {
            return MessageDigest.getInstance("SHA-256").digest(data);
        } catch (GeneralSecurityException e) {
            throw new IllegalStateException(e);
        }
    }

    public static byte[] hmacSha256(byte[] key, byte[] data) {
        return hmacSha256(key, data, 0, data.length);
    }

    public static byte[] hmacSha256(byte[] key, byte[] data, int off, int len) {
        try {
            Mac mac = Mac.getInstance("HmacSHA256");
            mac.init(new SecretKeySpec(key, "HmacSHA256"));
            mac.update(data, off, len);
            return mac.doFinal();
        } catch (GeneralSecurityException e) {
            throw new IllegalStateException(e);
        }
    }

    /**
     * HKDF-Extract + HKDF-Expand from RFC 5869.
     */
    public static byte[] hkdf(byte[] ikm, byte[] salt, byte[] info, int length) {
        byte[] prk = hmacSha256(salt.length == 0 ? new byte[32] : salt, ikm);
        return hkdfExpand(prk, info, length);
    }

    /**
     * HKDF-Expand with an already extracted pseudo-random key.
     */
    public static byte[] hkdfExpand(byte[] prk, byte[] info, int length) {
        if (length < 0 || length > 255 * 32) {
            throw new IllegalArgumentException("invalid HKDF length");
        }
        try {
            Mac mac = Mac.getInstance("HmacSHA256");
            mac.init(new SecretKeySpec(prk, "HmacSHA256"));
            byte[] out = new byte[length];
            byte[] previous = new byte[0];
            int pos = 0;
            byte counter = 1;
            while (pos < length) {
                mac.update(previous);
                mac.update(info);
                mac.update(counter);
                previous = mac.doFinal();
                int copy = Math.min(previous.length, length - pos);
                System.arraycopy(previous, 0, out, pos, copy);
                pos += copy;
                counter++;
            }
            return out;
        } catch (GeneralSecurityException e) {
            throw new IllegalStateException(e);
        }
    }

    /**
     * Portable PBKDF2-HMAC-SHA256 (implemented here so behavior is identical on
     * desktop Java 8 and Android).
     */
    public static byte[] pbkdf2(char[] password, byte[] salt, int iterations, int keyLengthBytes) {
        if (iterations < 1) {
            throw new IllegalArgumentException("iterations must be positive");
        }
        byte[] passwordBytes = new String(password).getBytes(StandardCharsets.UTF_8);
        try {
            Mac mac = Mac.getInstance("HmacSHA256");
            mac.init(new SecretKeySpec(passwordBytes, "HmacSHA256"));
            int hLen = mac.getMacLength();
            byte[] out = new byte[keyLengthBytes];
            int blocks = (keyLengthBytes + hLen - 1) / hLen;
            byte[] blockIndex = new byte[4];
            int pos = 0;
            for (int block = 1; block <= blocks; block++) {
                blockIndex[0] = (byte) (block >>> 24);
                blockIndex[1] = (byte) (block >>> 16);
                blockIndex[2] = (byte) (block >>> 8);
                blockIndex[3] = (byte) block;
                mac.update(salt);
                mac.update(blockIndex);
                byte[] u = mac.doFinal();
                byte[] t = u.clone();
                for (int i = 1; i < iterations; i++) {
                    u = mac.doFinal(u);
                    for (int j = 0; j < t.length; j++) {
                        t[j] ^= u[j];
                    }
                }
                int copy = Math.min(t.length, keyLengthBytes - pos);
                System.arraycopy(t, 0, out, pos, copy);
                pos += copy;
                Arrays.fill(t, (byte) 0);
                Arrays.fill(u, (byte) 0);
            }
            return out;
        } catch (GeneralSecurityException e) {
            throw new IllegalStateException(e);
        } finally {
            Arrays.fill(passwordBytes, (byte) 0);
        }
    }

    public static KeyPair generateEcKeyPair() {
        try {
            KeyPairGenerator generator = KeyPairGenerator.getInstance("EC");
            generator.initialize(new ECGenParameterSpec("secp256r1"), RANDOM);
            return generator.generateKeyPair();
        } catch (GeneralSecurityException e) {
            throw new IllegalStateException(e);
        }
    }

    public static byte[] encodeEcPublicKey(PublicKey key) {
        if (!(key instanceof ECPublicKey)) {
            throw new IllegalArgumentException("not an EC public key");
        }
        ECPoint point = ((ECPublicKey) key).getW();
        if (ECPoint.POINT_INFINITY.equals(point)) {
            throw new IllegalArgumentException("invalid EC point");
        }
        byte[] out = new byte[1 + P256_FIELD_BYTES * 2];
        out[0] = 0x04;
        writeFixed(point.getAffineX(), out, 1, P256_FIELD_BYTES);
        writeFixed(point.getAffineY(), out, 1 + P256_FIELD_BYTES, P256_FIELD_BYTES);
        return out;
    }

    public static PublicKey decodeEcPublicKey(byte[] encoded) {
        if (encoded == null || encoded.length != 1 + P256_FIELD_BYTES * 2 || encoded[0] != 0x04) {
            throw new IllegalArgumentException("invalid P-256 public key");
        }
        BigInteger x = new BigInteger(1, Arrays.copyOfRange(encoded, 1, 1 + P256_FIELD_BYTES));
        BigInteger y = new BigInteger(1, Arrays.copyOfRange(encoded, 1 + P256_FIELD_BYTES, encoded.length));
        EllipticCurve curve = P256.getCurve();
        BigInteger p = ((ECFieldFp) curve.getField()).getP();
        if (x.signum() < 0 || y.signum() < 0 || x.compareTo(p) >= 0 || y.compareTo(p) >= 0) {
            throw new IllegalArgumentException("invalid P-256 point");
        }
        // Reject points that are not on the curve. This avoids feeding invalid
        // points to the provider before KeyAgreement has a chance to validate.
        BigInteger left = y.multiply(y).mod(p);
        BigInteger right = x.pow(3).add(curve.getA().multiply(x)).add(curve.getB()).mod(p);
        if (!left.equals(right)) {
            throw new IllegalArgumentException("point is not on P-256");
        }
        try {
            ECPublicKeySpec spec = new ECPublicKeySpec(new ECPoint(x, y), P256);
            return KeyFactory.getInstance("EC").generatePublic(spec);
        } catch (GeneralSecurityException e) {
            throw new IllegalArgumentException("invalid P-256 public key", e);
        }
    }

    public static byte[] ecdh(PrivateKey privateKey, PublicKey publicKey) {
        try {
            KeyAgreement agreement = KeyAgreement.getInstance("ECDH");
            agreement.init(privateKey);
            agreement.doPhase(publicKey, true);
            return agreement.generateSecret();
        } catch (GeneralSecurityException e) {
            throw new IllegalArgumentException("ECDH failed", e);
        }
    }

    public static byte[] aesGcmEncrypt(byte[] key, byte[] nonce, byte[] aad, byte[] plaintext,
                                       int offset, int length) {
        try {
            Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
            cipher.init(Cipher.ENCRYPT_MODE, new SecretKeySpec(key, "AES"),
                    new GCMParameterSpec(128, nonce));
            cipher.updateAAD(aad);
            return cipher.doFinal(plaintext, offset, length);
        } catch (GeneralSecurityException e) {
            throw new IllegalStateException("AES-GCM encrypt failed", e);
        }
    }

    public static byte[] aesGcmDecrypt(byte[] key, byte[] nonce, byte[] aad, byte[] ciphertext)
            throws GeneralSecurityException {
        Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
        cipher.init(Cipher.DECRYPT_MODE, new SecretKeySpec(key, "AES"),
                new GCMParameterSpec(128, nonce));
        cipher.updateAAD(aad);
        return cipher.doFinal(ciphertext);
    }

    public static byte[] nonce(byte[] prefix, long sequence) {
        byte[] nonce = new byte[12];
        System.arraycopy(prefix, 0, nonce, 0, 4);
        nonce[4] = (byte) (sequence >>> 56);
        nonce[5] = (byte) (sequence >>> 48);
        nonce[6] = (byte) (sequence >>> 40);
        nonce[7] = (byte) (sequence >>> 32);
        nonce[8] = (byte) (sequence >>> 24);
        nonce[9] = (byte) (sequence >>> 16);
        nonce[10] = (byte) (sequence >>> 8);
        nonce[11] = (byte) sequence;
        return nonce;
    }

    public static boolean constantTimeEquals(byte[] a, byte[] b) {
        return MessageDigest.isEqual(a, b);
    }

    public static void wipe(byte[] value) {
        if (value != null) {
            Arrays.fill(value, (byte) 0);
        }
    }

    private static void writeFixed(BigInteger value, byte[] out, int offset, int length) {
        byte[] raw = value.toByteArray();
        int source = 0;
        if (raw.length > length && raw[0] == 0) {
            source = raw.length - length;
        }
        int copy = Math.min(length, raw.length - source);
        if (copy < length) {
            Arrays.fill(out, offset, offset + length - copy, (byte) 0);
        }
        System.arraycopy(raw, source, out, offset + length - copy, copy);
    }
}
