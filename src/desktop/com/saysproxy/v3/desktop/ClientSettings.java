package com.saysproxy.v3.desktop;

import java.io.IOException;
import java.io.InputStreamReader;
import java.io.OutputStreamWriter;
import java.io.Reader;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.nio.file.StandardOpenOption;
import java.util.Properties;

/**
 * Persists the desktop client's non-account credentials between runs.
 *
 * Stored: server host/port, server connection password, account name and local
 * proxy port. The account password is deliberately NEVER written to disk.
 *
 * The server connection password is a high-entropy shared secret generated by
 * the server. It is stored in a user-profile file, not encrypted at rest, so
 * protect the Windows/macOS/Linux account and the file itself.
 */
final class ClientSettings {
    private static final String KEY_SERVER_HOST = "serverHost";
    private static final String KEY_SERVER_PORT = "serverPort";
    private static final String KEY_CONNECTION_PASSWORD = "connectionPassword";
    private static final String KEY_USERNAME = "username";
    private static final String KEY_LOCAL_PORT = "localPort";

    private final Path file;

    private ClientSettings(Path file) {
        this.file = file;
    }

    static ClientSettings forCurrentUser() {
        String appData = System.getenv("APPDATA");
        Path directory;
        if (appData != null && !appData.trim().isEmpty()) {
            directory = Paths.get(appData.trim(), "SaysProxyV3");
        } else {
            directory = Paths.get(System.getProperty("user.home", "."), ".saysproxyv3");
        }
        return new ClientSettings(directory.resolve("client.properties"));
    }

    Path getFile() {
        return file;
    }

    Data load() throws IOException {
        Data data = new Data();
        if (!Files.exists(file)) {
            return data;
        }
        Properties properties = new Properties();
        try (Reader reader = new InputStreamReader(Files.newInputStream(file), StandardCharsets.UTF_8)) {
            properties.load(reader);
        }
        data.serverHost = properties.getProperty(KEY_SERVER_HOST, "").trim();
        data.serverPort = parseInt(properties.getProperty(KEY_SERVER_PORT), data.serverPort);
        data.connectionPassword = properties.getProperty(KEY_CONNECTION_PASSWORD, "");
        data.username = properties.getProperty(KEY_USERNAME, "").trim();
        data.localPort = parseInt(properties.getProperty(KEY_LOCAL_PORT), data.localPort);
        return data;
    }

    void save(Data data) throws IOException {
        Path parent = file.getParent();
        if (parent != null) {
            Files.createDirectories(parent);
        }
        Properties properties = new Properties();
        properties.setProperty(KEY_SERVER_HOST, nullToEmpty(data.serverHost));
        properties.setProperty(KEY_SERVER_PORT, Integer.toString(data.serverPort));
        properties.setProperty(KEY_CONNECTION_PASSWORD, nullToEmpty(data.connectionPassword));
        properties.setProperty(KEY_USERNAME, nullToEmpty(data.username));
        properties.setProperty(KEY_LOCAL_PORT, Integer.toString(data.localPort));

        Path temp = file.resolveSibling(file.getFileName().toString() + ".tmp");
        try (Writer writer = new OutputStreamWriter(Files.newOutputStream(temp,
                StandardOpenOption.CREATE, StandardOpenOption.TRUNCATE_EXISTING,
                StandardOpenOption.WRITE), StandardCharsets.UTF_8)) {
            properties.store(writer,
                    "SaysProxyV3 desktop settings. Contains the server connection password; the account password is NOT stored.");
        }
        try {
            Files.move(temp, file, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
        } catch (AtomicMoveNotSupportedException e) {
            Files.move(temp, file, StandardCopyOption.REPLACE_EXISTING);
        }
        restrictPermissions();
    }

    private void restrictPermissions() {
        try {
            Files.setPosixFilePermissions(file,
                    java.nio.file.attribute.PosixFilePermissions.fromString("rw-------"));
        } catch (UnsupportedOperationException ignored) {
            // Windows does not expose POSIX permissions here.
        } catch (IOException ignored) {
            // Best effort only.
        }
    }

    private static int parseInt(String value, int defaultValue) {
        if (value == null || value.trim().isEmpty()) {
            return defaultValue;
        }
        try {
            int parsed = Integer.parseInt(value.trim());
            if (parsed < 1 || parsed > 65535) {
                return defaultValue;
            }
            return parsed;
        } catch (NumberFormatException e) {
            return defaultValue;
        }
    }

    private static String nullToEmpty(String value) {
        return value == null ? "" : value;
    }

    static final class Data {
        String serverHost = "";
        int serverPort = 8388;
        String connectionPassword = "";
        String username = "";
        int localPort = 1080;
    }
}
